import assert from 'node:assert/strict'
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { after, test } from 'node:test'
import { parseProcedure } from './procedures.mjs'
import { proceduresBlock, renderProceduresBlock, skillGenerators } from './skills.mjs'
import { checkGenerated, sync } from './vendor.mjs'

const dirs = []
after(() => dirs.forEach((dir) => rmSync(dir, { recursive: true, force: true })))
const write = (root, files) =>
  Object.entries(files).forEach(([path, text]) => {
    mkdirSync(dirname(join(root, path)), { recursive: true })
    writeFileSync(join(root, path), text)
  })

const procedures = [
  parseProcedure(
    '---\nname: start-it\ndescription: Use when starting it.\ninvocation: explicit\n---\n\nRun `{{commands.lint}}` first.\n'
  ),
  parseProcedure(
    '---\nname: look-around\ndescription: Use when looking around.\ninvocation: auto\n---\n\nLook, per {{rel:documents.method}}.\n'
  )
]
const profile = (runtimes) => ({
  adapters: { stacks: ['node-ts'], runtimes, host: 'github' },
  commands: { lint: 'run-lint' },
  documents: { method: 'harness/core/method/method.md' }
})
// The runtime adapter of the framework, loaded from its folder
const { ADAPTER_RUNTIMES } = await import('./runtimes.mjs')

test('the Claude Code preset packages each procedure as a skill, explicit ones with disable-model-invocation', () => {
  const generators = skillGenerators(ADAPTER_RUNTIMES, procedures)
  assert.deepEqual(
    generators.map(({ id }) => id),
    ['skill-claude-code-start-it', 'skill-claude-code-look-around']
  )
  const [explicit, auto] = generators
  assert.equal(explicit.path(profile(['claude-code'])), '.claude/skills/start-it/SKILL.md')
  assert.equal(explicit.path(profile([])), undefined, 'a project without the runtime gets no skill')
  assert.equal(explicit.path({ ...profile(['claude-code']), documents: undefined }), undefined)
  assert.equal(
    explicit.render({ profile: profile(['claude-code']) }),
    '---\nname: start-it\ndescription: Use when starting it.\ndisable-model-invocation: true\n---\n\n<!-- Generated by `harness sync` from harness/core/procedures/start-it.md; do not edit this file. -->\n\nRun `run-lint` first.\n'
  )
  assert.doesNotMatch(auto.render({ profile: profile(['claude-code']) }), /disable-model-invocation/)
  assert.match(
    auto.render({ profile: profile(['claude-code']) }),
    /Look, per \.\.\/\.\.\/\.\.\/harness\/core\/method\/method\.md\./
  )
})

test('the entry file lists the procedures for every agent, with or without a runtime, relative to the entry file', () => {
  assert.equal(
    renderProceduresBlock(profile([]), procedures),
    '| When | Follow the procedure |\n| ---- | -------------------- |\n| starting it | [`harness/core/procedures/start-it.md`](./harness/core/procedures/start-it.md) |\n| looking around | [`harness/core/procedures/look-around.md`](./harness/core/procedures/look-around.md) |'
  )
  assert.match(
    renderProceduresBlock({ ...profile([]), paths: { entryFile: 'docs/AGENTS.md' } }, procedures),
    /\(\.\.\/harness\/core\/procedures\/start-it\.md\)/
  )
  assert.equal(proceduresBlock.path(profile([])), 'AGENTS.md')
  assert.equal(proceduresBlock.path({}), undefined)
})

// A project with a vendored copy, so that sync and check generated work on it
function project() {
  const root = mkdtempSync(join(tmpdir(), 'skills-'))
  dirs.push(root)
  write(root, {
    'harness-profile.json': JSON.stringify(profile(['claude-code'])),
    'framework/framework.json': JSON.stringify({
      name: 'harness-framework',
      version: '0.1.0-dev',
      distributable: ['core', 'adapters']
    }),
    'framework/core/x.md': 'x\n',
    'framework/adapters/stack/node-ts/manifest.json': '{}',
    'framework/adapters/runtime/claude-code/manifest.json': '{}',
    'framework/adapters/host/github/manifest.json': '{}'
  })
  sync({ root, from: 'framework', generators: [] })
  return root
}

test('check generated fails on a stale or missing skill and passes after a sync', () => {
  const root = project()
  const generators = skillGenerators(ADAPTER_RUNTIMES, procedures)
  const skill = join(root, '.claude/skills/start-it/SKILL.md')
  sync({ root, local: true, generators })
  assert.deepEqual(checkGenerated({ root, generators }), [])
  assert.match(readFileSync(skill, 'utf8'), /^---\nname: start-it/)

  writeFileSync(skill, readFileSync(skill, 'utf8').replace('first', 'second'))
  assert.match(
    checkGenerated({ root, generators }).join('\n'),
    /the managed file \.claude\/skills\/start-it\/SKILL\.md is not what/
  )
  sync({ root, local: true, generators })
  assert.deepEqual(checkGenerated({ root, generators }), [])

  rmSync(skill)
  assert.match(checkGenerated({ root, generators }).join('\n'), /start-it\/SKILL\.md/)
  sync({ root, local: true, generators })
  assert.deepEqual(checkGenerated({ root, generators }), [])
})

test('a procedure that changed in the framework without a sync makes the skill stale', () => {
  const root = project()
  sync({ root, local: true, generators: skillGenerators(ADAPTER_RUNTIMES, procedures) })
  const changed = [{ ...procedures[0], body: 'Run `{{commands.lint}}` last.\n' }, procedures[1]]
  assert.match(
    checkGenerated({ root, generators: skillGenerators(ADAPTER_RUNTIMES, changed) }).join('\n'),
    /start-it\/SKILL\.md is not what the tools generate now/
  )
})
