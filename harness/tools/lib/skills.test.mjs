import assert from 'node:assert/strict'
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { after, test } from 'node:test'
import { listProcedures, listProjectProcedures, parseProcedure } from './procedures.mjs'
import { proceduresBlock, projectSkillGenerator, renderProceduresBlock, skillGenerators } from './skills.mjs'
import { checkGenerated, sync } from './vendor.mjs'

const dirs = []
after(() => dirs.forEach((dir) => rmSync(dir, { recursive: true, force: true })))
const write = (root, files) =>
  Object.entries(files).forEach(([path, text]) => {
    mkdirSync(dirname(join(root, path)), { recursive: true })
    writeFileSync(join(root, path), text)
  })

const procedures = [
  parseProcedure(
    '---\nname: start-it\ndescription: Use when starting it.\ninvocation: explicit\n---\n\nRun `{{commands.lint}}` first.\n'
  ),
  parseProcedure(
    '---\nname: look-around\ndescription: Use when looking around.\ninvocation: auto\n---\n\nLook, per {{rel:documents.method}}.\n'
  )
]
const profile = (runtimes) => ({
  adapters: { stacks: ['node-ts'], runtimes, host: 'github' },
  commands: { lint: 'run-lint' },
  documents: { method: 'harness/core/method/method.md' }
})
// The runtime adapter of the framework, loaded from its folder
const { ADAPTER_RUNTIMES } = await import('./runtimes.mjs')

test('the Claude Code preset packages each procedure as a skill, explicit ones with disable-model-invocation', () => {
  const generators = skillGenerators(ADAPTER_RUNTIMES, procedures)
  assert.deepEqual(
    generators.map(({ id }) => id),
    ['skill-claude-code-start-it', 'skill-claude-code-look-around', 'skill-cursor-start-it', 'skill-cursor-look-around']
  )
  const [explicit, auto] = generators
  assert.equal(explicit.path(profile(['claude-code'])), '.claude/skills/start-it/SKILL.md')
  assert.equal(explicit.path(profile([])), undefined, 'a project without the runtime gets no skill')
  assert.equal(explicit.path({ ...profile(['claude-code']), documents: undefined }), undefined)
  assert.equal(
    explicit.render({ profile: profile(['claude-code']) }),
    '---\nname: start-it\ndescription: Use when starting it.\ndisable-model-invocation: true\n---\n\n<!-- Generated by `harness sync` from harness/core/procedures/start-it.md; do not edit this file. -->\n\nRun `run-lint` first.\n'
  )
  assert.doesNotMatch(auto.render({ profile: profile(['claude-code']) }), /disable-model-invocation/)
  assert.match(
    auto.render({ profile: profile(['claude-code']) }),
    /Look, per \.\.\/\.\.\/\.\.\/harness\/core\/method\/method\.md\./
  )
})

test('the Cursor preset packages the skills under .cursor/skills when it is the only runtime, and none next to Claude Code', () => {
  const [, , explicit] = skillGenerators(ADAPTER_RUNTIMES, procedures)
  assert.equal(explicit.path(profile(['cursor'])), '.cursor/skills/start-it/SKILL.md')
  assert.match(
    explicit.render({ profile: profile(['cursor']) }),
    /^---\nname: start-it\n.*disable-model-invocation: true/s
  )
  assert.equal(
    explicit.path(profile(['claude-code', 'cursor'])),
    undefined,
    'Cursor loads the skills of .claude/skills'
  )
  assert.equal(explicit.path(profile([])), undefined)
})

test('the entry file lists the procedures for every agent, with or without a runtime, relative to the entry file', () => {
  assert.equal(
    renderProceduresBlock(profile([]), procedures),
    '| When | Follow the procedure |\n| ---- | -------------------- |\n| starting it | [`harness/core/procedures/start-it.md`](./harness/core/procedures/start-it.md) |\n| looking around | [`harness/core/procedures/look-around.md`](./harness/core/procedures/look-around.md) |'
  )
  assert.match(
    renderProceduresBlock({ ...profile([]), paths: { entryFile: 'docs/AGENTS.md' } }, procedures),
    /\(\.\.\/harness\/core\/procedures\/start-it\.md\)/
  )
  assert.equal(proceduresBlock.path(profile([])), 'AGENTS.md')
  assert.equal(proceduresBlock.path({}), undefined)
})

// A project with a vendored copy, so that sync and check generated work on it
function project() {
  const root = mkdtempSync(join(tmpdir(), 'skills-'))
  dirs.push(root)
  write(root, {
    'harness-profile.json': JSON.stringify(profile(['claude-code'])),
    'framework/framework.json': JSON.stringify({
      name: 'harness-framework',
      version: '0.1.0-dev',
      distributable: ['core', 'adapters']
    }),
    'framework/core/x.md': 'x\n',
    'framework/adapters/stack/node-ts/manifest.json': '{}',
    'framework/adapters/runtime/claude-code/manifest.json': '{}',
    'framework/adapters/host/github/manifest.json': '{}'
  })
  sync({ root, from: 'framework', generators: [] })
  return root
}

test('check generated fails on a stale or missing skill and passes after a sync', () => {
  const root = project()
  const generators = skillGenerators(ADAPTER_RUNTIMES, procedures)
  const skill = join(root, '.claude/skills/start-it/SKILL.md')
  sync({ root, local: true, generators })
  assert.deepEqual(checkGenerated({ root, generators }), [])
  assert.match(readFileSync(skill, 'utf8'), /^---\nname: start-it/)

  writeFileSync(skill, readFileSync(skill, 'utf8').replace('first', 'second'))
  assert.match(
    checkGenerated({ root, generators }).join('\n'),
    /the managed file \.claude\/skills\/start-it\/SKILL\.md is not what/
  )
  sync({ root, local: true, generators })
  assert.deepEqual(checkGenerated({ root, generators }), [])

  rmSync(skill)
  assert.match(checkGenerated({ root, generators }).join('\n'), /start-it\/SKILL\.md/)
  sync({ root, local: true, generators })
  assert.deepEqual(checkGenerated({ root, generators }), [])
})

test('a procedure that changed in the framework without a sync makes the skill stale', () => {
  const root = project()
  sync({ root, local: true, generators: skillGenerators(ADAPTER_RUNTIMES, procedures) })
  const changed = [{ ...procedures[0], body: 'Run `{{commands.lint}}` last.\n' }, procedures[1]]
  assert.match(
    checkGenerated({ root, generators: skillGenerators(ADAPTER_RUNTIMES, changed) }).join('\n'),
    /start-it\/SKILL\.md is not what the tools generate now/
  )
})

// A project with one procedure of its own in docs/procedures, packaged for the selected runtimes
const ownProcedure = (name, header = 'invocation: auto') =>
  `---\nname: ${name}\ndescription: Use when adding an endpoint.\n${header}\n---\n\nRun \`{{commands.lint}}\`, then see {{rel:documents.method}}.\n`
const withOwn = (runtimes, files = { 'docs/procedures/add-endpoint.md': ownProcedure('add-endpoint') }) => {
  const root = mkdtempSync(join(tmpdir(), 'own-skills-'))
  dirs.push(root)
  write(root, files)
  return { root, profile: { ...profile(runtimes), paths: { procedures: 'docs/procedures' } } }
}

test('a procedure of the project is packaged for the selected runtimes, with its own file named as the source', () => {
  const { root, profile: own } = withOwn(['claude-code'])
  const [skill] = projectSkillGenerator(ADAPTER_RUNTIMES).expand({ root, profile: own })
  assert.equal(skill.path, '.claude/skills/add-endpoint/SKILL.md')
  assert.equal(
    skill.content,
    '---\nname: add-endpoint\ndescription: Use when adding an endpoint.\n---\n\n<!-- Generated by `harness sync` from docs/procedures/add-endpoint.md; do not edit this file. -->\n\nRun `run-lint`, then see ../../../harness/core/method/method.md.\n'
  )

  const cursor = withOwn(['cursor'])
  assert.deepEqual(
    projectSkillGenerator(ADAPTER_RUNTIMES)
      .expand(cursor)
      .map(({ path }) => path),
    ['.cursor/skills/add-endpoint/SKILL.md']
  )
  const both = withOwn(['claude-code', 'cursor'])
  assert.deepEqual(
    projectSkillGenerator(ADAPTER_RUNTIMES)
      .expand(both)
      .map(({ path }) => path),
    ['.claude/skills/add-endpoint/SKILL.md']
  )
})

test('a project without a runtime, without the role or without a document map has no skill of its own', () => {
  const generator = projectSkillGenerator(ADAPTER_RUNTIMES)
  const none = withOwn([])
  assert.deepEqual(generator.expand(none), [])
  const noRole = withOwn(['claude-code'])
  assert.deepEqual(generator.expand({ root: noRole.root, profile: profile(['claude-code']) }), [])
  assert.deepEqual(generator.expand({ ...noRole, profile: { ...noRole.profile, documents: undefined } }), [])
})

test("the procedures block lists the procedures of the project after the framework's, relative to the entry file", () => {
  const { root, profile: own } = withOwn([])
  const rendered = proceduresBlock.render({ root, profile: own })
  const rows = rendered.split('\n')
  assert.match(
    rows.at(-1),
    /^\| adding an endpoint \| \[`docs\/procedures\/add-endpoint\.md`\]\(\.\/docs\/procedures\/add-endpoint\.md\) \|$/
  )
  assert.match(rows[2], /harness\/core\/procedures\//)
  assert.match(
    renderProceduresBlock(
      { ...own, paths: { ...own.paths, entryFile: 'docs/AGENTS.md' } },
      listProjectProcedures(root, own)
    ),
    /\(\.\/procedures\/add-endpoint\.md\)/
  )
})

test('a procedure of the project that has the name of one of the framework is refused', () => {
  const { root, profile: own } = withOwn([], { 'docs/procedures/release.md': ownProcedure('release') })
  assert.throws(
    () => proceduresBlock.render({ root, profile: own }),
    /docs\/procedures: the procedure "release" has the name of a procedure of the framework/
  )
})

test('check generated fails on a stale skill of a procedure of the project and passes after a sync', () => {
  const root = project()
  write(root, { 'docs/procedures/add-endpoint.md': ownProcedure('add-endpoint') })
  writeFileSync(
    join(root, 'harness-profile.json'),
    JSON.stringify({ ...profile(['claude-code']), paths: { procedures: 'docs/procedures' } })
  )
  const generators = [projectSkillGenerator(ADAPTER_RUNTIMES)]
  const skill = join(root, '.claude/skills/add-endpoint/SKILL.md')
  assert.match(
    checkGenerated({ root, generators }).join('\n'),
    /add-endpoint\/SKILL\.md is not what the tools generate/
  )
  sync({ root, local: true, generators })
  assert.deepEqual(checkGenerated({ root, generators }), [])

  write(root, { 'docs/procedures/add-endpoint.md': ownProcedure('add-endpoint').replace('then see', 'then read') })
  assert.match(
    checkGenerated({ root, generators }).join('\n'),
    /add-endpoint\/SKILL\.md is not what the tools generate/
  )
  sync({ root, local: true, generators })
  assert.match(readFileSync(skill, 'utf8'), /then read/)
  assert.deepEqual(checkGenerated({ root, generators }), [])

  write(root, { 'docs/procedures/release.md': ownProcedure('release') })
  assert.throws(
    () => sync({ root, local: true, generators: [...generators, proceduresBlock] }),
    /has the name of a procedure of the framework/
  )
})

// The invocation of the procedures of the framework: the work the method requires of every agent unasked can be loaded by the agent (design §8.1)
test('the procedures that every agent starts unasked are auto, and the explicit ones are those a person starts or that act outside the repository', () => {
  const invocation = Object.fromEntries(listProcedures().map(({ name, invocation }) => [name, invocation]))
  for (const name of [
    'start-task',
    'end-session',
    'finish-phase',
    'open-pull-request',
    'change-plan',
    'triage-reports'
  ]) {
    assert.equal(invocation[name], 'auto', name)
  }
  for (const name of [
    'release',
    'code-review',
    'harness-review',
    'new-adapter',
    'update-framework',
    'report-upstream'
  ]) {
    assert.equal(invocation[name], 'explicit', name)
  }
  for (const procedure of listProcedures().filter(({ invocation: kind }) => kind === 'auto')) {
    const packaged = ADAPTER_RUNTIMES['claude-code'].modules['packaging.mjs'].packageProcedure(procedure, 'Body.')
    assert.doesNotMatch(packaged, /disable-model-invocation/, procedure.name)
  }
  for (const procedure of listProcedures().filter(({ invocation: kind }) => kind === 'explicit')) {
    const packaged = ADAPTER_RUNTIMES['claude-code'].modules['packaging.mjs'].packageProcedure(procedure, 'Body.')
    assert.match(packaged, /disable-model-invocation: true/, procedure.name)
  }
})
