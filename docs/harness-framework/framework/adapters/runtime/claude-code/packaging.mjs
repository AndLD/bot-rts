// The Claude Code preset's packaging of the neutral procedures (design §8.1, role "procedure packaging"): each becomes the skill
// `.claude/skills/<name>/SKILL.md`, with `name` and `description` in its frontmatter, and `disable-model-invocation: true` for an explicit one, so that
// it runs when invoked as `/<name>` and not on the model's own judgment.

/** The path of the skill for a procedure. */
export const skillPath = (procedure) => `.claude/skills/${procedure.name}/SKILL.md`

/** The text of the skill: the frontmatter, a note that it is generated, and the rendered body. */
export function packageProcedure(procedure, body) {
  const header = [
    '---',
    `name: ${procedure.name}`,
    `description: ${procedure.description}`,
    ...(procedure.invocation === 'explicit' ? ['disable-model-invocation: true'] : []),
    ...(procedure.paths ? [`paths: ${procedure.paths.join(', ')}`] : []),
    '---',
    '',
    `<!-- Generated by \`harness sync\` from harness/core/procedures/${procedure.name}.md; do not edit this file. -->`,
    ''
  ]
  return `${header.join('\n')}\n${body.replace(/\n+$/, '')}\n`
}
